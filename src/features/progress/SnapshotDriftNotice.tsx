import { useState } from "react";
import { View } from "react-native";

import { AppButton, AppText, MaskedValue } from "@/src/components/common";
import type { SavedSnapshotRecalculation, SnapshotRecordDrift } from "@/src/domain/calculations";
import { isAutoGeneratedSnapshotProvisional } from "@/src/domain/calculations/monthEndSnapshots";
import { formatINR } from "@/src/domain/formatters";
import type { MonthlySnapshot } from "@/src/types";

import { useStyles } from "./monthlyHistoryStyles";

export type MonthRecalculation = {
  /** Works out a saved month again from current records and prices, saving nothing. */
  preview: (month: string) => SavedSnapshotRecalculation;
  /** Saves the recalculated month exactly as the user compared it. */
  replace: (snapshot: MonthlySnapshot) => { ok: true } | { ok: false; reason: string };
};

const comparedRows = [
  { field: "portfolioValue", label: "Portfolio value" },
  { field: "equityValue", label: "Equity" },
  { field: "debtValue", label: "Debt" },
  { field: "cryptoValue", label: "Crypto" },
  { field: "cashValue", label: "Cash" },
  { field: "investedValue", label: "Invested basis" },
  { field: "monthlyInvestment", label: "Monthly investment" },
] as const;

/**
 * A saved month that no longer matches current records (#747): says so, and
 * replaces it with the recalculated month only after the user compares the two.
 */
export function SnapshotDriftNotice({
  drift,
  maskWealthValues,
  recalculation,
}: {
  drift: SnapshotRecordDrift;
  maskWealthValues: boolean;
  recalculation: MonthRecalculation;
}) {
  const styles = useStyles();
  const [recalculated, setRecalculated] = useState<MonthlySnapshot | null>(null);
  const [failure, setFailure] = useState<string | null>(null);
  const estimated = recalculated !== null && isAutoGeneratedSnapshotProvisional(recalculated);

  return (
    <View style={styles.driftNotice} testID="snapshot-drift-notice">
      <AppText weight="bold">Saved before later records were added</AppText>
      <AppText color="secondary" variant="caption">
        Records dated in or before this month were added or changed after it was saved, so its values don&apos;t
        match your records. Month gain for this month and the next is unavailable until it&apos;s recalculated.
      </AppText>
      {recalculated ? (
        <>
          <View style={styles.comparisonColumns}>
            <AppText color="secondary" style={styles.comparisonColumn} variant="caption">Saved</AppText>
            <AppText color="secondary" style={[styles.comparisonColumn, styles.currentColumn]} variant="caption">
              From records
            </AppText>
          </View>
          {comparedRows.map(({ field, label }) => (
            <View key={field} style={styles.driftRow} testID={`snapshot-drift-row-${field}`}>
              <AppText>{label}</AppText>
              <View style={styles.comparisonColumns}>
                <View style={styles.comparisonColumn}>
                  <MaskedValue exactValue={formatINR(drift.saved[field])} masked={maskWealthValues}
                    testID={`snapshot-drift-saved-${field}`} value={formatINR(drift.saved[field])} />
                </View>
                <View style={[styles.comparisonColumn, styles.currentColumn]}>
                  <MaskedValue align="right" exactValue={formatINR(recalculated[field])} masked={maskWealthValues}
                    testID={`snapshot-drift-recalculated-${field}`} value={formatINR(recalculated[field])} weight="bold" />
                </View>
              </View>
            </View>
          ))}
          {estimated ? (
            <AppText color="secondary" variant="caption">
              Some month-end prices are estimates; CogVest will update them when better prices are available.
            </AppText>
          ) : null}
          <AppText color="secondary" variant="caption">
            Replacing marks this month as automatic. Your records are not changed.
          </AppText>
          <AppButton
            onPress={() => {
              const result = recalculation.replace(recalculated);
              if (!result.ok) setFailure(result.reason);
            }}
            testID="confirm-recalculate-snapshot"
            title="Replace saved values"
          />
          <AppButton onPress={() => { setRecalculated(null); setFailure(null); }} testID="cancel-recalculate-snapshot"
            title="Keep saved values" variant="secondary" />
        </>
      ) : (
        <AppButton
          onPress={() => {
            const result = recalculation.preview(drift.month);
            if (result.ok) {
              setRecalculated(result.snapshot);
              setFailure(null);
            } else setFailure(result.reason);
          }}
          testID="recalculate-snapshot"
          title="Recalculate from records"
          variant="secondary"
        />
      )}
      {failure ? (
        <AppText accessibilityRole="alert" color="secondary" testID="recalculate-snapshot-error" variant="caption">
          {failure}
        </AppText>
      ) : null}
    </View>
  );
}
