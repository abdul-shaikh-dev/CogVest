import type { ReactNode } from "react";
import { View } from "react-native";

import { AppText, assetClassLabel, CategoryIcon, MaskedValue } from "@/src/components/common";
import {
  type MonthlyProgressSummary,
  percentageChange,
  snapshotAssetClassValues,
  snapshotSourceLabel,
  type SnapshotRecordDrift,
} from "@/src/domain/calculations";
import { isAutoGeneratedSnapshotProvisional } from "@/src/domain/calculations/monthEndSnapshots";
import { calculateSnapshotInvestedComparison } from "@/src/domain/calculations/snapshotInvestedComparison";
import { formatINR, formatPercentage } from "@/src/domain/formatters";

import { useStyles } from "./monthlyHistoryStyles";
import { SnapshotDriftNotice, type MonthRecalculation } from "./SnapshotDriftNotice";
import { formatShortMonth, formatSignedValue, getAssetAllocation } from "./monthlyHistoryViewModel";

export function MonthDetail({
  drift,
  maskWealthValues,
  minimal,
  recalculation,
  previousSummary,
  summary,
}: {
  /** Set when this saved month no longer matches current records (#747). */
  drift?: SnapshotRecordDrift;
  maskWealthValues: boolean;
  minimal: boolean;
  recalculation?: MonthRecalculation;
  previousSummary: MonthlyProgressSummary | undefined;
  summary: MonthlyProgressSummary;
}) {
  const styles = useStyles();
  const snapshot = summary.snapshot;
  const investedComparison = calculateSnapshotInvestedComparison(snapshot);
  const previousSnapshot = previousSummary?.snapshot;
  const portfolioChange = percentageChange(
    snapshot.portfolioValue,
    previousSnapshot?.portfolioValue,
  );
  const estimated = isAutoGeneratedSnapshotProvisional(snapshot) ||
    (previousSnapshot !== undefined && isAutoGeneratedSnapshotProvisional(previousSnapshot));
  const assetMetrics = snapshotAssetClassValues(snapshot, previousSnapshot);
  const capitalRows = [
    {
      label: "Total portfolio change",
      signed: true,
      value: previousSummary ? summary.performance.totalValueChange : null,
    },
    { label: "Monthly investment", value: snapshot.monthlyInvestment },
    { label: "Net contribution", signed: true, value: summary.performance.netExternalFlow },
    {
      label: "Market change",
      signed: true,
      value: previousSummary ? summary.performance.marketMovement : null,
    },
  ];

  return (
    <View style={styles.detail} testID="selected-snapshot-summary">
      <AppText color="secondary" variant="caption">Month-end portfolio value</AppText>
      <MaskedValue
        exactValue={formatINR(snapshot.portfolioValue)}
        masked={maskWealthValues}
        style={styles.detailPortfolio}
        value={formatINR(snapshot.portfolioValue)}
        weight="bold"
      />
      <AppText
        color="secondary"
        style={portfolioChange !== null ? portfolioChange < 0 ? styles.lossText : styles.gainText : undefined}
        variant="caption"
        weight="bold"
      >
        {portfolioChange === null
          ? previousSummary ? "Percentage unavailable · prior value was zero" : "Previous month unavailable"
          : formatPercentage(portfolioChange)} portfolio value change
      </AppText>
      {estimated ? (
        <AppText color="secondary" variant="caption">
          {previousSummary ? "This comparison uses estimated prices." : "This month-end value uses estimated prices."}
        </AppText>
      ) : null}
      <AppText color="secondary" variant="caption">
        Portfolio change includes deposits and withdrawals; it is not investment return.
      </AppText>
      <AppText color="secondary" testID="snapshot-source" variant="caption">
        Values: {snapshotSourceLabel(snapshot)}
      </AppText>
      {drift && recalculation ? (
        <SnapshotDriftNotice drift={drift} key={drift.month} maskWealthValues={maskWealthValues} recalculation={recalculation} />
      ) : null}

      <DetailSection title="Vs invested">
        <AppText
          color="secondary"
          style={investedComparison && investedComparison.percentage !== 0
            ? investedComparison.percentage < 0 ? styles.lossText : styles.gainText : undefined}
          testID="snapshot-invested-percentage"
          variant="title"
          weight="bold"
        >
          {investedComparison ? formatPercentage(investedComparison.percentage) : "Unavailable"}
        </AppText>
        <DetailRow label="Investments, excluding cash" maskWealthValues={maskWealthValues} value={investedComparison?.investmentValue} />
        <DetailRow label="Recorded invested basis" maskWealthValues={maskWealthValues} value={investedComparison?.investedValue} />
        <DetailRow label="Difference vs invested" maskWealthValues={maskWealthValues} signed value={investedComparison?.difference} />
        <AppText color="secondary" variant="caption">
          Uses this month's recorded basis for investments still held, including any PPF balance checkpoint. Excludes cash and sold holdings. Not monthly return or lifetime profit.
        </AppText>
        {!investedComparison ? <AppText color="secondary" variant="caption">Comparison needs valid recorded values and a positive invested basis.</AppText> : null}
      </DetailSection>

      <DetailSection title="What changed">
        <View style={styles.comparisonColumns} testID="snapshot-comparison-heading">
          <AppText color="secondary" variant="caption" style={styles.comparisonColumn}>
            {previousSummary ? `${formatShortMonth(previousSummary.snapshot.month)} ${previousSummary.snapshot.month.slice(0, 4)}` : "Previous month unavailable"}
          </AppText>
          <AppText color="secondary" variant="caption" style={[styles.comparisonColumn, styles.currentColumn]}>
            {`${formatShortMonth(snapshot.month)} ${snapshot.month.slice(0, 4)}`}
          </AppText>
        </View>
        {assetMetrics.map((metric) => {
          const change = percentageChange(metric.current, metric.previous);
          const allocation = getAssetAllocation(summary, metric.assetClass);
          const detail = allocation === undefined
            ? "Allocation unavailable"
            : `${formatPercentage(allocation).replace("+", "")} allocation`;

          return (
            <View key={metric.assetClass} style={styles.comparisonRow}>
              <View style={styles.comparisonIdentity}>
              <View style={styles.assetLabel}>
                <CategoryIcon assetClass={metric.assetClass} size={18} />
                <View style={styles.detailRowLabel}>
                  <AppText weight="bold">{assetClassLabel(metric.assetClass)}</AppText>
                  <AppText color="secondary" variant="caption">{detail}</AppText>
                </View>
              </View>
                <AppText
                  color="secondary"
                  style={change !== null ? change < 0 ? styles.lossText : styles.gainText : undefined}
                  variant="caption"
                >
                  {change === null ? "—" : formatPercentage(change)}
                </AppText>
              </View>
              <View style={styles.comparisonColumns}>
                <View style={styles.comparisonColumn}>
                  <MaskedValue masked={maskWealthValues && metric.previous !== undefined}
                    accessibilityLabel={metric.previous === undefined ? "Previous value unavailable" : undefined}
                    value={metric.previous === undefined ? "—" : formatINR(metric.previous)}
                    exactValue={metric.previous === undefined ? undefined : formatINR(metric.previous)} />
                </View>
                <View style={[styles.comparisonColumn, styles.currentColumn]}>
                  <MaskedValue exactValue={formatINR(metric.current)} masked={maskWealthValues}
                    value={formatINR(metric.current)} weight="bold" align="right" />
                </View>
              </View>
            </View>
          );
        })}
      </DetailSection>

      <DetailSection title="Capital & cash flow">
        {capitalRows.map((row) => (
          <DetailRow
            key={row.label}
            label={row.label}
            maskWealthValues={maskWealthValues}
            signed={row.signed}
            value={row.value}
          />
        ))}
      </DetailSection>

      {snapshot.notes && !maskWealthValues ? (
        <AppText color="secondary" variant="caption">{snapshot.notes}</AppText>
      ) : null}
    </View>
  );
}

function DetailSection({ children, title }: { children: ReactNode; title: string }) {
  const styles = useStyles();
  return (
    <View style={styles.detailSection}>
      <AppText variant="title" weight="bold">{title}</AppText>
      {children}
    </View>
  );
}

function DetailRow({
  label,
  maskWealthValues,
  percentage = false,
  signed = false,
  value,
}: {
  label: string;
  maskWealthValues: boolean;
  percentage?: boolean;
  signed?: boolean;
  value: number | null | undefined;
}) {
  const styles = useStyles();
  const displayValue = value === null || value === undefined
    ? "Unavailable"
    : percentage
      ? formatPercentage(value).replace("+", "")
      : signed
        ? formatSignedValue(value)
        : formatINR(value);

  return (
    <View style={styles.detailRow}>
      <AppText style={styles.detailRowLabel}>{label}</AppText>
      <MaskedValue
        align="right"
        masked={maskWealthValues && !percentage && value !== null && value !== undefined}
        value={displayValue}
        valueType={percentage ? "percentage" : "wealth"}
        weight="bold"
      />
    </View>
  );
}
