import { useEffect, useRef, useState } from "react";
import {
  AccessibilityInfo,
  findNodeHandle,
  Modal,
  Pressable,
  ScrollView,
  type ScrollViewInstance,
  View,
  type ViewInstance,
} from "react-native";
import { useSafeAreaInsets } from "react-native-safe-area-context";

import {
  AppButton,
  AppText,
  MaskedValue,
  androidRipple,
  getPressedStateStyle,
} from "@/src/components/common";
import type { MonthlyProgressSummary } from "@/src/domain/calculations";
import { isAutoGeneratedSnapshotProvisional } from "@/src/domain/calculations/monthEndSnapshots";
import { calculateSnapshotInvestedComparison } from "@/src/domain/calculations/snapshotInvestedComparison";
import { formatCompactINR, formatINR, formatPercentage } from "@/src/domain/formatters";
import { useSingleBackRequest } from "@/src/hooks";
import { spacing } from "@/src/theme";

import { MonthDetail } from "./MonthDetail";
import { useStyles } from "./monthlyHistoryStyles";
import {
  formatMonth,
  formatShortMonth,
  historyYears,
  previousCalendarMonth,
  yearOverview,
} from "./monthlyHistoryViewModel";

type MonthlyHistoryPanelProps = {
  maskWealthValues: boolean;
  minimal: boolean;
  summaries: MonthlyProgressSummary[];
};

export function MonthlyHistoryPanel({
  maskWealthValues,
  minimal,
  summaries,
}: MonthlyHistoryPanelProps) {
  const styles = useStyles();
  const insets = useSafeAreaInsets();
  const [isVisible, setIsVisible] = useState(false);
  const [selectedYear, setSelectedYear] = useState("");
  const [selectedMonth, setSelectedMonth] = useState<string | null>(null);
  const scrollRef = useRef<ScrollViewInstance>(null);
  const overviewScrollOffsetRef = useRef(0);
  const isRestoringOverviewRef = useRef(false);
  const rowRefs = useRef<Record<string, ViewInstance | null>>({});
  const originMonthRef = useRef<string | null>(null);

  const summariesByMonth = new Map(
    summaries.map((summary) => [summary.snapshot.month, summary]),
  );
  const years = historyYears(summaries);
  const selectedSummary = selectedMonth
    ? summariesByMonth.get(selectedMonth)
    : undefined;
  const isDetailVisible = Boolean(selectedSummary);
  const {
    barWidth,
    months: overviewSummaries,
    showValueBars,
  } = yearOverview(summaries, selectedYear, maskWealthValues);

  const normalizedYear = !years.length
    ? ""
    : years.includes(selectedYear) ? selectedYear : years[0];
  if (normalizedYear !== selectedYear) setSelectedYear(normalizedYear);

  useEffect(() => {
    if (!isVisible) return;

    let frame: number;
    if (isDetailVisible) {
      isRestoringOverviewRef.current = false;
      frame = requestAnimationFrame(() => {
        scrollRef.current?.scrollTo({ animated: false, y: 0 });
      });
    } else if (isRestoringOverviewRef.current) {
      const originMonth = originMonthRef.current;
      const restoreOffset = overviewScrollOffsetRef.current;

      // Wait for the overview rows to mount before restoring scroll and focus.
      frame = requestAnimationFrame(() => {
        frame = requestAnimationFrame(() => {
          scrollRef.current?.scrollTo({ animated: false, y: restoreOffset });
          const origin = originMonth ? rowRefs.current[originMonth] : null;
          const handle = origin ? findNodeHandle(origin) : null;

          if (handle) AccessibilityInfo.setAccessibilityFocus(handle);
          frame = requestAnimationFrame(() => {
            isRestoringOverviewRef.current = false;
          });
        });
      });
    } else {
      return;
    }

    return () => cancelAnimationFrame(frame);
  }, [isDetailVisible, isVisible]);

  const handleBackRequest = useSingleBackRequest(requestClose);

  if (!summaries.length) return null;

  function openHistory() {
    setSelectedYear(years[0]);
    setSelectedMonth(null);
    overviewScrollOffsetRef.current = 0;
    isRestoringOverviewRef.current = false;
    originMonthRef.current = null;
    setIsVisible(true);
  }

  function closeHistory() {
    setIsVisible(false);
    setSelectedMonth(null);
    isRestoringOverviewRef.current = false;
  }

  function openMonth(month: string) {
    originMonthRef.current = month;
    setSelectedMonth(month);
  }

  function showOverview() {
    isRestoringOverviewRef.current = true;
    setSelectedMonth(null);
  }

  function requestClose() {
    if (selectedMonth) {
      showOverview();
    } else {
      closeHistory();
    }
  }

  return (
    <>
      <View testID="monthly-history-panel">
        <AppButton
          accessibilityLabel="Open monthly history"
          onPress={openHistory}
          testID="open-monthly-history"
          title="History"
          variant="ghost"
        />
      </View>

      <Modal
        animationType="none"
        onRequestClose={handleBackRequest}
        testID="monthly-history-modal"
        transparent
        visible={isVisible}
      >
        <View style={[styles.modalBackdrop, { paddingTop: insets.top }]}>
          <View
            accessibilityViewIsModal
            style={[
              styles.sheet,
              { paddingBottom: Math.max(insets.bottom, spacing.md), paddingTop: spacing.md },
            ]}
          >
            <View style={styles.sheetHeader}>
              {isDetailVisible ? (
                <Pressable
                  accessibilityLabel="Back to monthly history"
                  accessibilityRole="button"
                  android_ripple={androidRipple()}
                  onPress={showOverview}
                  style={({ pressed }) => [styles.headerButton, getPressedStateStyle({ pressed })]}
                  testID="history-back"
                >
                  <AppText weight="bold">Back</AppText>
                </Pressable>
              ) : (
                <View style={styles.headerButton} />
              )}
              <AppText align="center" style={styles.sheetTitle} variant="title" weight="bold">
                {selectedSummary ? formatMonth(selectedSummary.snapshot.month) : "Monthly History"}
              </AppText>
              <Pressable
                accessibilityLabel="Close monthly history"
                accessibilityRole="button"
                android_ripple={androidRipple()}
                onPress={closeHistory}
                style={({ pressed }) => [styles.headerButton, getPressedStateStyle({ pressed })]}
                testID="close-monthly-history"
              >
                <AppText color="secondary" weight="bold">Close</AppText>
              </Pressable>
            </View>

            <ScrollView
              contentContainerStyle={styles.sheetContent}
              onScroll={(event) => {
                if (!selectedMonth && !isRestoringOverviewRef.current) {
                  overviewScrollOffsetRef.current = event.nativeEvent.contentOffset.y;
                }
              }}
              ref={scrollRef}
              scrollEventThrottle={16}
              testID="monthly-history-scroll"
            >
              {selectedSummary ? (
                <MonthDetail
                  maskWealthValues={maskWealthValues}
                  minimal={minimal}
                  previousSummary={summariesByMonth.get(previousCalendarMonth(selectedSummary.snapshot.month))}
                  summary={selectedSummary}
                />
              ) : (
                <>
                  <AppText color="secondary" variant="caption">
                    Vs invested excludes cash
                  </AppText>
                  <ScrollView
                    accessibilityLabel="History year"
                    horizontal
                    nestedScrollEnabled
                    showsHorizontalScrollIndicator={false}
                    style={styles.yearScroll}
                    testID="history-year-scroll"
                  >
                    <View accessibilityRole="tablist" style={styles.yearList}>
                      {years.map((year) => {
                        const isSelected = selectedYear === year;

                        return (
                          <Pressable
                            accessibilityRole="tab"
                            accessibilityState={{ selected: isSelected }}
                            android_ripple={androidRipple()}
                            key={year}
                            onPress={() => setSelectedYear(year)}
                            style={({ pressed }) => [
                              styles.yearButton,
                              isSelected ? styles.yearButtonSelected : null,
                              getPressedStateStyle({ pressed }),
                            ]}
                            testID={`history-year-${year}`}
                          >
                            <AppText color={isSelected ? "inverse" : "secondary"} weight="bold">
                              {year}
                            </AppText>
                          </Pressable>
                        );
                      })}
                    </View>
                  </ScrollView>
                  {showValueBars ? (
                    <AppText color="secondary" variant="caption" testID="history-bar-scale">
                      Bars: portfolio value relative to {selectedYear}'s highest month
                    </AppText>
                  ) : null}
                  <View style={styles.historyColumns}>
                    <AppText color="secondary" style={styles.historyMonthColumn} variant="caption">Month</AppText>
                    <AppText align="right" color="secondary" style={styles.historyValueColumn} variant="caption">Portfolio</AppText>
                    <AppText align="right" color="secondary" style={styles.historyChangeColumn} variant="caption">Vs invested</AppText>
                    <View style={styles.historyChevronColumn} />
                  </View>
                  {overviewSummaries.map((summary) => {
                    const month = summary.snapshot.month;
                    const comparison = calculateSnapshotInvestedComparison(summary.snapshot);
                    const change = comparison?.percentage ?? null;
                    const estimated = isAutoGeneratedSnapshotProvisional(summary.snapshot);
                    // Percentages stay visible when values are masked, as Settings says.
                    const changeAccessibility = change === null ? "Comparison unavailable; requires valid recorded values and a positive invested basis"
                        : `${formatPercentage(change)} versus this month's recorded invested basis, excluding cash`;

                    return (
                      <Pressable
                        accessibilityLabel={`View ${formatMonth(month)} details. Portfolio ${
                          maskWealthValues ? "hidden" : formatINR(summary.snapshot.portfolioValue)
                        }. ${changeAccessibility}.${estimated ? " Month-end value uses estimated prices." : ""}`}
                        accessibilityRole="button"
                        android_ripple={androidRipple()}
                        key={summary.snapshot.id}
                        onPress={() => openMonth(month)}
                        ref={(node) => {
                          rowRefs.current[month] = node;
                        }}
                        style={({ pressed }) => [styles.historyRow, getPressedStateStyle({ pressed })]}
                        testID={`snapshot-month-${month}`}
                      >
                        <View style={styles.historyNumbers}>
                          <View style={styles.historyMonthColumn}>
                            <AppText weight="bold">{formatShortMonth(month)}</AppText>
                            {estimated ? (
                              <AppText color="secondary" variant="caption">Estimated</AppText>
                            ) : null}
                          </View>
                          <MaskedValue
                            align="right"
                            exactValue={formatINR(summary.snapshot.portfolioValue)}
                            masked={maskWealthValues}
                            style={styles.historyValueColumn}
                            value={formatCompactINR(summary.snapshot.portfolioValue)}
                            weight="bold"
                          />
                          <AppText
                            align="right"
                            color={change === null ? "secondary" : "primary"}
                            testID={`snapshot-invested-comparison-${month}`}
                            style={[
                              styles.historyChangeColumn,
                              change !== null && change !== 0 ? change < 0 ? styles.lossText : styles.gainText : undefined,
                            ]}
                            weight="bold"
                          >
                            {change === null ? "—" : formatPercentage(change)}
                          </AppText>
                          <AppText color="secondary" style={[styles.chevron, styles.historyChevronColumn]} weight="bold">›</AppText>
                        </View>
                        {showValueBars ? (
                          <View accessible={false} importantForAccessibility="no-hide-descendants" style={styles.historyTrack}>
                            <View testID={`snapshot-value-bar-${month}`} style={[
                              styles.historyBar,
                              { width: barWidth(summary.snapshot.portfolioValue) },
                            ]} />
                          </View>
                        ) : null}
                      </Pressable>
                    );
                  })}
                </>
              )}
            </ScrollView>
          </View>
        </View>
      </Modal>
    </>
  );
}
