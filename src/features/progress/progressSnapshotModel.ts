export function emptyProgressFormValues() {
  const now = new Date();

  return {
    cashValue: "",
    cryptoValue: "",
    debtValue: "",
    equityValue: "",
    investedValue: "",
    month: `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}`,
    monthlyInvestment: "",
    notes: "",
    portfolioValue: "",
  };
}

export type ProgressFormValues = ReturnType<typeof emptyProgressFormValues>;
export type ProgressFormErrors = Partial<Record<keyof ProgressFormValues, string>>;

export type ProgressSnapshotStatusKind =
  | "checking"
  | "complete"
  | "empty"
  | "estimated"
  | "generating"
  | "incomplete-ppf"
  | "missing-price"
  | "records-incomplete"
  | "waiting-for-first-month"
  | "reconstructed-history";

export type SnapshotAutomationProgress = {
  checkedCount: number;
  currentMonth: string;
  totalCount: number;
};

export type SnapshotAutomationStatusState = {
  message: string;
  pendingMonths: string[];
  progress: SnapshotAutomationProgress | null;
  provisionalMonths: string[];
  snapshot: MonthlySnapshot | null;
  status: GeneratedSnapshotStatus | "idle";
  targetMonth: string;
  warnings: string[];
};

export type ProgressSnapshotAutomationStatus = SnapshotAutomationStatusState & {
  availableThroughMonth: string | null;
  kind: ProgressSnapshotStatusKind;
};

export type MonthEndSnapshotAutomationRunResult = {
  createdCount: number;
  lastCompletedMonth: string;
  pendingMonths: string[];
  provisionalCount: number;
  provisionalMonths: string[];
  refreshedCount: number;
  snapshot: MonthlySnapshot | null;
  status: GeneratedSnapshotStatus;
  targetMonths: string[];
  warnings: string[];
};

export function getSnapshotStatusKind({
  hasData,
  hasStoredHistory,
  hasIncompletePpfHistory,
  hasReconstructedHistory,
  status,
}: {
  hasData: boolean;
  hasStoredHistory: boolean;
  hasIncompletePpfHistory: boolean;
  hasReconstructedHistory: boolean;
  status: SnapshotAutomationStatusState;
}): ProgressSnapshotStatusKind {
  if (status.progress) return "generating";
  if (!hasData) return "empty";
  if (hasReconstructedHistory) return "reconstructed-history";
  if (hasIncompletePpfHistory) return "incomplete-ppf";
  if (status.warnings.some((warning) => warning.includes("Earlier PPF balances"))) {
    return "incomplete-ppf";
  }
  if (
    status.warnings.some(
      (warning) =>
        warning.includes("Refresh prices") ||
        warning.includes("pending valuation") ||
        warning.includes("could not be priced"),
    )
  ) {
    return "missing-price";
  }
  if (status.warnings.length > 0) return "records-incomplete";
  if (status.provisionalMonths.length > 0) return "estimated";
  if (status.status === "idle") return "checking";
  if (status.status === "insufficient-data" && !hasStoredHistory) return "waiting-for-first-month";
  return "complete";
}

export function getIncompletePpfHistoryMonths(
  accounts: PpfAccount[],
  lastCompletedMonth: string,
) {
  const missingMonths = new Set<string>();

  for (const account of accounts) {
    if (account.legacyAssetId) continue;

    const openingMonth = getPpfAccountOpeningDate(account).slice(0, 7);
    const firstConfirmedMonth = account.balanceAsOf.slice(0, 7);
    let cursor = new Date(`${openingMonth}-01T12:00:00Z`);

    while (Number.isFinite(cursor.getTime())) {
      const month = cursor.toISOString().slice(0, 7);
      if (month >= firstConfirmedMonth || month > lastCompletedMonth) break;
      missingMonths.add(month);
      cursor = new Date(Date.UTC(cursor.getUTCFullYear(), cursor.getUTCMonth() + 1, 1, 12));
    }
  }

  return [...missingMonths].sort();
}

function getAvailableSnapshotMonths(snapshots: MonthlySnapshot[]) {
  return [...new Set(snapshots.map((snapshot) => snapshot.month))].sort();
}

export function getDefaultCustomChartRange(
  snapshots: MonthlySnapshot[],
): MonthlyChartCustomRange {
  const months = getAvailableSnapshotMonths(snapshots);

  return {
    endMonth: months.at(-1) ?? "",
    startMonth: months[0] ?? "",
  };
}

export function normalizeCustomChartRange(
  current: MonthlyChartCustomRange,
  snapshots: MonthlySnapshot[],
) {
  const months = getAvailableSnapshotMonths(snapshots);
  const startMonth = months.includes(current.startMonth)
    ? current.startMonth
    : months[0] ?? "";
  const endMonth = months.includes(current.endMonth)
    ? current.endMonth
    : months.at(-1) ?? "";

  if (startMonth >= endMonth) {
    return {
      endMonth: months.at(-1) ?? "",
      startMonth: months[0] ?? "",
    };
  }

  return { endMonth, startMonth };
}

const requiredNumberFields: Array<keyof ProgressFormValues> = [
  "portfolioValue",
  "investedValue",
  "equityValue",
  "debtValue",
  "cryptoValue",
  "cashValue",
  "monthlyInvestment",
];

function parseNumberField(
  values: ProgressFormValues,
  field: keyof ProgressFormValues,
  errors: ProgressFormErrors,
) {
  const value = values[field].trim();
  const parsedValue = value.length > 0 ? Number(value) : Number.NaN;

  if (!Number.isFinite(parsedValue)) {
    errors[field] = "Enter a valid amount.";
  }

  return parsedValue;
}

export function validateProgressSnapshotForm(values: ProgressFormValues) {
  const errors: ProgressFormErrors = {};

  if (!/^\d{4}-\d{2}$/.test(values.month.trim())) {
    errors.month = "Use YYYY-MM.";
  }

  const parsedValues = Object.fromEntries(
    requiredNumberFields.map((field) => [
      field,
      parseNumberField(values, field, errors),
    ]),
  ) as Record<(typeof requiredNumberFields)[number], number>;
  if (Object.keys(errors).length > 0) {
    return { errors, snapshot: null };
  }

  const candidate = {
    cashValue: parsedValues.cashValue,
    cryptoValue: parsedValues.cryptoValue,
    debtValue: parsedValues.debtValue,
    equityValue: parsedValues.equityValue,
    id: createId("snapshot"),
    investedValue: parsedValues.investedValue,
    month: values.month.trim(),
    monthlyInvestment: parsedValues.monthlyInvestment,
    notes: values.notes.trim() || undefined,
    performanceBasis: {
      reason: "manual-snapshot",
      status: "unavailable",
      warnings: [
        "Monthly performance is unavailable because this snapshot has no classified external-flow basis.",
      ],
    },
    portfolioValue: parsedValues.portfolioValue,
  } satisfies MonthlySnapshot;
  const domainErrors = validateMonthlySnapshot(candidate);
  return { errors: domainErrors, snapshot: Object.keys(domainErrors).length ? null : candidate };
}

export function automationMessage({
  createdCount,
  pendingMonths,
  provisionalCount,
  refreshedCount,
  status,
  warnings = [],
}: {
  createdCount: number;
  pendingMonths: string[];
  provisionalCount: number;
  refreshedCount: number;
  status: GeneratedSnapshotStatus;
  warnings?: string[];
}) {
  if (warnings.some((warning) => warning.startsWith("Earlier PPF balances"))) {
    return "Full portfolio history needs earlier PPF balances. PPF is excluded from available market and cash trends.";
  }
  if (refreshedCount > 0) {
    return refreshedCount === 1
      ? "1 estimated snapshot updated with better month-end values."
      : `${refreshedCount} estimated snapshots updated with better month-end values.`;
  }

  if (
    pendingMonths.length > 0 &&
    warnings.some(
      (warning) =>
        warning.includes("Refresh prices") ||
        warning.includes("pending valuation") ||
        warning.includes("could not be priced"),
    )
  ) {
    return pendingMonths.length === 1
      ? "1 month is waiting for a historical price."
      : `${pendingMonths.length} months are waiting for historical prices.`;
  }

  if (pendingMonths.length > 0) {
    return pendingMonths.length === 1
      ? "1 month could not be completed from the recorded portfolio data."
      : `${pendingMonths.length} months could not be completed from the recorded portfolio data.`;
  }

  if (status === "created") {
    return createdCount === 1
      ? "1 missing month snapshot generated automatically."
      : `${createdCount} missing month snapshots generated automatically.`;
  }

  if (provisionalCount > 0) {
    return "Some completed months still use estimated values.";
  }

  if (status === "already-exists") {
    return "All completed month snapshots are already recorded.";
  }

  return "The first monthly snapshot will be created after a full portfolio month is complete.";
}

/** The status shown once an automation run, or a check with nothing to run, finishes. */
export function automationStatusFromResult(
  result: MonthEndSnapshotAutomationRunResult,
): SnapshotAutomationStatusState {
  return {
    message: automationMessage(result),
    pendingMonths: result.pendingMonths,
    progress: null,
    provisionalMonths: result.provisionalMonths,
    snapshot: result.snapshot,
    status: result.status,
    targetMonth: result.lastCompletedMonth,
    warnings: result.warnings,
  };
}

export function automationWarningMessage(targetMonth: string, warning: string) {
  if (warning.includes("PPF account") && warning.includes("confirmed balance checkpoint")) {
    return "Earlier PPF balances are missing. Today's PPF balance cannot be used for past months. Add a confirmed earlier balance only if your statement supports it; market and cash charts exclude PPF until its history is available.";
  }
  if (warning.includes("fallback")) {
    return null;
  }

  if (warning.includes("could not be priced")) {
    return warning.includes(targetMonth) ? warning : `${targetMonth}: ${warning}`;
  }

  if (warning.includes("could not be valued")) {
    return `${targetMonth}: ${warning}`;
  }

  const demerger = /^(\d+) holdings? used verified demerger cost basis before listing/u.exec(warning);
  if (demerger) {
    const count = Number(demerger[1]);
    return `${targetMonth}: ${count === 1 ? "A demerged holding is" : `${count} demerged holdings are`} valued at verified cost until the new shares list. No action is needed.`;
  }

  // Show the specific reason; a generic "needs review" leaves no way to find the record.
  return `${targetMonth}: ${warning}`;
}

export function summarizeMonthlyWarnings(warnings: string[]) {
  const uniqueWarnings = [...new Set(warnings)];
  const groups = new Map<string, { months: string[]; prefix: string; suffix: string }>();
  const ungrouped: string[] = [];

  for (const warning of uniqueWarnings) {
    const match = /^(.*) for (\d{4}-\d{2})(:.*)$/.exec(warning);
    if (!match) {
      ungrouped.push(warning);
      continue;
    }

    const key = `${match[1]}${match[3]}`;
    const group = groups.get(key) ?? { months: [], prefix: match[1], suffix: match[3] };
    group.months.push(match[2]);
    groups.set(key, group);
  }

  return [
    ...ungrouped,
    ...[...groups.values()].map(({ months, prefix, suffix }) => {
      const orderedMonths = [...new Set(months)].sort();
      if (orderedMonths.length === 1) {
        return `${prefix} for ${orderedMonths[0]}${suffix}`;
      }

      return `${prefix} across ${orderedMonths.length} months (${orderedMonths[0]} to ${orderedMonths.at(-1)})${suffix}`;
    }),
  ];
}

export function getSnapshotAutomationTargetMonths({
  now,
  retryProvisional = true,
  state,
}: {
  now: Date;
  retryProvisional?: boolean;
  state: PortfolioStoreState;
}) {
  const lastCompletedMonth = getPreviousCompletedMonth(now);
  const missingMonths = getMissingCompletedSnapshotMonths({
    cashEntries: state.cashEntries,
    existingSnapshots: state.monthlySnapshots,
    now,
    openingPositions: state.openingPositions,
    ppfAccounts: state.ppfAccounts,
    trades: state.trades,
  });
  const provisionalMonths = retryProvisional
    ? state.monthlySnapshots
        .filter(
          (snapshot) =>
            snapshot.month <= lastCompletedMonth &&
            isAutoGeneratedSnapshotProvisional(snapshot) &&
            snapshot.generated?.priceEvidence !== undefined,
        )
        .map((snapshot) => snapshot.month)
    : [];
  return [
    ...new Set([...missingMonths, ...provisionalMonths]),
  ].sort();
}

function getProvisionalSnapshotMonths({
  lastCompletedMonth,
  snapshots,
}: {
  lastCompletedMonth: string;
  snapshots: MonthlySnapshot[];
}) {
  return snapshots
    .filter(
      (snapshot) =>
        snapshot.month <= lastCompletedMonth &&
        getMonthlySnapshotPriceConfidence(snapshot) === "provisional",
    )
    .map((snapshot) => snapshot.month)
    .sort();
}

function getMonthEndDate(targetMonth: string) {
  const [yearValue, monthValue] = targetMonth.split("-");
  const year = Number(yearValue);
  const monthIndex = Number(monthValue) - 1;

  return new Date(Date.UTC(year, monthIndex + 1, 0, 23, 59, 59, 999));
}

function isOnOrBefore(isoDate: string, maxDate: Date) {
  return new Date(isoDate).getTime() <= maxDate.getTime();
}

/** The stored history through the last completed month, used to report a run's outcome. */
export function getCompletedMonthState(
  state: PortfolioStoreState,
  lastCompletedMonth: string,
) {
  const latestCompletedSnapshot = [...state.monthlySnapshots]
    .filter((monthlySnapshot) => monthlySnapshot.month <= lastCompletedMonth)
    .sort((left, right) => right.month.localeCompare(left.month))[0] ?? null;
  const hasCompletedPortfolioRecord = [
    ...state.cashEntries.map((entry) => entry.date),
    ...state.openingPositions.map((position) =>
      getOpeningPositionHistoryDate(position),
    ),
    ...state.trades.map((trade) => trade.date),
    ...state.ppfAccounts.map((account) => account.balanceAsOf),
  ].some(
    (date) =>
      date !== null &&
      isOnOrBefore(date, getMonthEndDate(lastCompletedMonth)),
  );
  const provisionalMonths = getProvisionalSnapshotMonths({
    lastCompletedMonth,
    snapshots: state.monthlySnapshots,
  });

  return { hasCompletedPortfolioRecord, latestCompletedSnapshot, provisionalMonths };
}

export function needsHistoricalPrice({
  assetId,
  state,
  targetMonth,
}: {
  assetId: string;
  state: PortfolioStoreState;
  targetMonth: string;
}) {
  const cacheKey = historicalQuoteCacheKey(assetId, targetMonth);
  const cachedQuote = state.historicalQuoteCache[cacheKey];

  if (
    cachedQuote?.currency === "INR" &&
    (cachedQuote.basis === "historical-close" ||
      cachedQuote.basis === "reconciled-historical-close" ||
      cachedQuote.basis === "cached-historical-close")
  ) {
    return false;
  }

  const monthEnd = getMonthEndDate(targetMonth);
  const effectiveOpenings = state.openingPositions.filter(
    (position) =>
      position.assetId === assetId &&
      isOnOrBefore(getOpeningPositionHistoryDate(position) ?? "", monthEnd),
  );
  const trades = state.trades.filter((trade) =>
    trade.assetId === assetId &&
    isOnOrBefore(trade.date, monthEnd) &&
    isTransactionAfterOpeningCutover(trade.date, effectiveOpenings),
  );
  try {
    const demergerAdjustments = projectDemergers({
      assets: state.assets,
      openingPositions: state.openingPositions,
      trades: state.trades,
    }, monthEnd.toISOString().slice(0, 10)).filter((adjustment) => adjustment.assetId === assetId);
    return positionQuantity({
      demergerAdjustments,
      openingPositions: effectiveOpenings,
      trades,
      stockSplits: state.assets.find((asset) => asset.id === assetId)?.stockSplits,
      through: monthEnd.toISOString().slice(0, 10),
    }).greaterThanOrEqualTo(quantityQuantum);
  } catch (error) {
    if (!(error instanceof StockSplitError)) throw error;
    return false;
  }
}

type ProgressPortfolioRecords = Pick<
  PortfolioStoreState,
  | "assets"
  | "cashEntries"
  | "openingPositions"
  | "ppfAccounts"
  | "ppfLedgerEntries"
  | "quoteCache"
  | "trades"
>;

/** Today's portfolio totals, allocation and this month's investment for Progress. */
export function calculateProgressPortfolio(
  records: ProgressPortfolioRecords,
  now: Date,
  asOf: string,
) {
  const ppfSummary = calculatePpfPortfolioSummary({
    accounts: records.ppfAccounts,
    asOf,
    entries: records.ppfLedgerEntries,
  });
  const linkedLegacyAssetIds = getLinkedLegacyPpfAssetIds(records.ppfAccounts, asOf);
  const holdings = calculateHoldings({
    assets: records.assets,
    openingPositions: records.openingPositions,
    quoteCache: records.quoteCache,
    trades: records.trades,
    now,
  }).filter((holding) => !linkedLegacyAssetIds.has(holding.asset.id));
  const cashBalance = calculateCashBalance(records.cashEntries, now);
  const portfolioValue = calculatePortfolioTotal(
    holdings,
    records.cashEntries,
    now,
    ppfSummary.confirmedBalance,
  );
  const totalInvested = normalizeMoney(
    sumFinancialValues(
      holdings.map(
        (holding) =>
          holding.calculationBasis?.totalInvested ?? holding.totalInvested,
      ),
    ).plus(ppfSummary.investedBasis),
  );
  const baseMonthlyMetrics = calculateCashMonthlyMetrics({
    cashEntries: records.cashEntries,
    now,
    openingPositions: records.openingPositions.filter(
      (position) => !linkedLegacyAssetIds.has(position.assetId),
    ),
    trades: records.trades.filter(
      (trade) => !linkedLegacyAssetIds.has(trade.assetId),
    ),
  });
  const currentMonth = formatLocalCalendarDate(now).slice(0, 7);
  const ppfMonthlyInvestment = normalizeMoney(
    sumFinancialValues(
      records.ppfLedgerEntries
        .filter(
          (entry) =>
            entry.type === "contribution" &&
            entry.date.slice(0, 7) === currentMonth,
        )
        .map((entry) => (entry.type === "contribution" ? entry.amount : 0)),
    ),
  );
  const monthlyInvested = normalizeMoney(
    decimal(baseMonthlyMetrics.invested).plus(ppfMonthlyInvestment),
  );
  const monthlyMetrics = {
    ...baseMonthlyMetrics,
    invested: monthlyInvested,
  };
  const allocation = calculateAllocation({
    cashBalance,
    holdings,
    ppfConfirmedBalance: ppfSummary.confirmedBalance,
  });
  const hasData =
    holdings.length > 0 ||
    records.cashEntries.length > 0 ||
    ppfSummary.accounts.length > 0;
  return { allocation, cashBalance, hasData, monthlyMetrics, portfolioValue, totalInvested };
}

/** Combines the automation state with stored and reconstructed history for the status card. */
export function presentSnapshotAutomationStatus({
  activeProgress,
  automationStatus,
  hasData,
  latestStoredSnapshot,
  now,
  ppfAccounts,
  reconstructedSnapshots,
}: {
  activeProgress: SnapshotAutomationProgress | null;
  automationStatus: SnapshotAutomationStatusState;
  hasData: boolean;
  latestStoredSnapshot: MonthlySnapshot | null;
  now: Date;
  ppfAccounts: PpfAccount[];
  reconstructedSnapshots: MonthlySnapshot[] | null;
}): ProgressSnapshotAutomationStatus {
  const displayedAutomationStatus: SnapshotAutomationStatusState =
    activeProgress
      ? {
          message: "Building monthly history.",
          pendingMonths: [],
          progress: activeProgress,
          provisionalMonths: [],
          snapshot: latestStoredSnapshot,
          status: "idle",
          targetMonth: activeProgress.currentMonth,
          warnings: [],
        }
      : automationStatus;
  const reconstructedThroughMonth = reconstructedSnapshots
    ? [...reconstructedSnapshots]
        .sort((left, right) => right.month.localeCompare(left.month))[0]?.month ?? null
    : null;
  const incompletePpfHistoryMonths = getIncompletePpfHistoryMonths(
    ppfAccounts,
    getPreviousCompletedMonth(now),
  );
  const presentedAutomationStatus = {
    ...displayedAutomationStatus,
    pendingMonths:
      displayedAutomationStatus.pendingMonths.length > 0
        ? displayedAutomationStatus.pendingMonths
        : incompletePpfHistoryMonths,
  };

  return {
    ...presentedAutomationStatus,
    availableThroughMonth:
      reconstructedThroughMonth ??
      displayedAutomationStatus.snapshot?.month ??
      latestStoredSnapshot?.month ??
      null,
    kind: getSnapshotStatusKind({
      hasData: hasData || latestStoredSnapshot !== null,
      hasStoredHistory: latestStoredSnapshot !== null,
      hasIncompletePpfHistory: incompletePpfHistoryMonths.length > 0,
      hasReconstructedHistory: reconstructedSnapshots !== null,
      status: presentedAutomationStatus,
    }),
  };
}
