import type { StoreApi } from "zustand/vanilla";

import {
  buildGeneratedMonthEndSnapshot,
  getPreviousCompletedMonth,
  isAutoGeneratedSnapshotProvisional,
  shouldReplaceProvisionalSnapshot,
  type GeneratedSnapshotStatus,
} from "@/src/domain/calculations";
import type { resolveHistoricalPrice } from "@/src/services/quotes";
import type { PortfolioStoreState } from "@/src/store";
import type { MonthlySnapshot } from "@/src/types";

import {
  automationWarningMessage,
  getCompletedMonthState,
  needsHistoricalPrice,
  summarizeMonthlyWarnings,
  type MonthEndSnapshotAutomationRunResult,
  type SnapshotAutomationProgress,
} from "./progressSnapshotModel";

// One run per store at a time, shared by every mounted useProgress.
export const inFlightSnapshotAutomationRuns = new WeakMap<
  StoreApi<PortfolioStoreState>,
  Promise<MonthEndSnapshotAutomationRunResult>
>();
export const snapshotAutomationEpochs = new WeakMap<StoreApi<PortfolioStoreState>, number>();

const snapshotAutomationProgress = new WeakMap<
  StoreApi<PortfolioStoreState>,
  SnapshotAutomationProgress
>();
const snapshotAutomationProgressListeners = new WeakMap<
  StoreApi<PortfolioStoreState>,
  Set<() => void>
>();

export function getSnapshotAutomationProgress(store: StoreApi<PortfolioStoreState>) {
  return snapshotAutomationProgress.get(store) ?? null;
}

export function publishSnapshotAutomationProgress(
  store: StoreApi<PortfolioStoreState>,
  progress: SnapshotAutomationProgress | null,
) {
  if (progress) {
    snapshotAutomationProgress.set(store, progress);
  } else {
    snapshotAutomationProgress.delete(store);
  }
  snapshotAutomationProgressListeners.get(store)?.forEach((listener) => listener());
}

export function subscribeToSnapshotAutomationProgress(
  store: StoreApi<PortfolioStoreState>,
  listener: () => void,
) {
  const listeners = snapshotAutomationProgressListeners.get(store) ?? new Set();
  listeners.add(listener);
  snapshotAutomationProgressListeners.set(store, listeners);

  return () => {
    listeners.delete(listener);
    if (listeners.size === 0) snapshotAutomationProgressListeners.delete(store);
  };
}

/** Fetches missing month-end prices and saves or refreshes each target month's snapshot. */
export async function runMonthEndSnapshotAutomation({
  historicalPriceFetcher,
  now,
  store,
  targetMonths,
}: {
  historicalPriceFetcher: typeof resolveHistoricalPrice;
  now: Date;
  store: StoreApi<PortfolioStoreState>;
  targetMonths: string[];
}): Promise<MonthEndSnapshotAutomationRunResult> {
  const lastCompletedMonth = getPreviousCompletedMonth(now);
  const restoreEpoch = store.getState().restoreEpoch;
  const cancelledResult: MonthEndSnapshotAutomationRunResult = {
    createdCount: 0, lastCompletedMonth,
    pendingMonths: [],
    provisionalCount: 0, provisionalMonths: [], refreshedCount: 0,
    snapshot: null, status: "insufficient-data", targetMonths: [], warnings: [],
  };
  const warnings: string[] = [];
  const createdSnapshots: MonthlySnapshot[] = [];
  const refreshedSnapshots: MonthlySnapshot[] = [];

  publishSnapshotAutomationProgress(store, {
    checkedCount: 0,
    currentMonth: targetMonths[0] ?? "",
    totalCount: targetMonths.length,
  });

  for (const [targetIndex, targetMonth] of targetMonths.entries()) {
    publishSnapshotAutomationProgress(store, {
      checkedCount: targetIndex,
      currentMonth: targetMonth,
      totalCount: targetMonths.length,
    });
    const state = store.getState();
    const existingSnapshot = state.monthlySnapshots.find(
      (snapshot) => snapshot.month === targetMonth,
    );
    const shouldRefreshPrices =
      existingSnapshot === undefined ||
      (isAutoGeneratedSnapshotProvisional(existingSnapshot) &&
        existingSnapshot.generated?.priceEvidence !== undefined);
    const quoteableAssets = state.assets.filter(
      (asset) => asset.assetClass !== "cash" && asset.assetClass !== "debt",
    );

    for (const asset of quoteableAssets) {
      if (
        !shouldRefreshPrices ||
        !needsHistoricalPrice({ assetId: asset.id, state, targetMonth })
      ) {
        continue;
      }

      const historicalPriceResult = await historicalPriceFetcher({
        asset,
        targetMonth,
      });

      if (store.getState().restoreEpoch !== restoreEpoch) {
        publishSnapshotAutomationProgress(store, null);
        return cancelledResult;
      }

      if (historicalPriceResult.ok) {
        store.getState().upsertHistoricalQuote(historicalPriceResult.quote);
      }
    }

    const refreshedState = store.getState();
    const result = buildGeneratedMonthEndSnapshot({
      assets: refreshedState.assets,
      cashEntries: refreshedState.cashEntries,
      existingSnapshots: refreshedState.monthlySnapshots,
      historicalQuotes: refreshedState.historicalQuoteCache,
      now,
      openingPositions: refreshedState.openingPositions,
      ppfAccounts: refreshedState.ppfAccounts,
      ppfLedgerEntries: refreshedState.ppfLedgerEntries,
      quoteCache: refreshedState.quoteCache,
      refreshProvisional: true,
      targetMonth,
      trades: refreshedState.trades,
    });

    warnings.push(
      ...result.warnings.flatMap((warning) => {
        const message = automationWarningMessage(targetMonth, warning);

        return message ? [message] : [];
      }),
    );

    if (result.status === "created" && result.snapshot) {
      const existingSnapshot = refreshedState.monthlySnapshots.find(
        (snapshot) => snapshot.month === targetMonth,
      );

      if (existingSnapshot) {
        if (
          shouldReplaceProvisionalSnapshot(
            existingSnapshot,
            result.snapshot,
          )
        ) {
          store.getState().updateMonthlySnapshot(result.snapshot);
          refreshedSnapshots.push(result.snapshot);
        }
      } else {
        store.getState().addMonthlySnapshot(result.snapshot);
        createdSnapshots.push(result.snapshot);
      }
    }

    publishSnapshotAutomationProgress(store, {
      checkedCount: targetIndex + 1,
      currentMonth: targetMonth,
      totalCount: targetMonths.length,
    });
  }

  const completedState = store.getState();
  const {
    hasCompletedPortfolioRecord,
    latestCompletedSnapshot,
    provisionalMonths,
  } = getCompletedMonthState(completedState, lastCompletedMonth);
  const unresolvedTargetMonths = targetMonths.filter(
    (targetMonth) =>
      !completedState.monthlySnapshots.some(
        (monthlySnapshot) => monthlySnapshot.month === targetMonth,
      ),
  );
  if (warnings.length === 0 && unresolvedTargetMonths.length > 0) {
    warnings.push(
      ...unresolvedTargetMonths.map(
        (targetMonth) =>
          `${targetMonth}: This snapshot could not be completed. Refresh prices or enter a manual price for holdings with pending valuation.`,
      ),
    );
  }
  const status: GeneratedSnapshotStatus =
    createdSnapshots.length > 0 || refreshedSnapshots.length > 0
      ? "created"
      : unresolvedTargetMonths.length > 0
        ? "insufficient-data"
      : hasCompletedPortfolioRecord
        ? "already-exists"
        : "insufficient-data";

  return {
    createdCount: createdSnapshots.length,
    lastCompletedMonth,
    pendingMonths: unresolvedTargetMonths,
    provisionalCount: provisionalMonths.length,
    provisionalMonths,
    refreshedCount: refreshedSnapshots.length,
    snapshot: latestCompletedSnapshot,
    status,
    targetMonths,
    warnings: summarizeMonthlyWarnings(warnings),
  };
}
