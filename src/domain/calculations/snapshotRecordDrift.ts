import type { MonthlySnapshot, QuoteCache } from "@/src/types";
import { decimal } from "@/src/domain/precision";

import {
  buildGeneratedMonthEndSnapshot,
  isAutoGeneratedSnapshotProvisional,
  type BuildGeneratedMonthEndSnapshotInput,
} from "./monthEndSnapshots";

/** The records a month is recalculated from; the month and saved history come separately. */
export type SnapshotDriftRecords = Omit<
  BuildGeneratedMonthEndSnapshotInput,
  "existingSnapshots" | "refreshProvisional" | "targetMonth"
>;

/**
 * Values that come from records alone, never from prices. A difference in any
 * of them means records dated on or before the month changed after it was
 * saved; a price moving never shows up here.
 */
export const snapshotDriftFields = ["investedValue", "cashValue", "monthlyInvestment"] as const;
export type SnapshotDriftField = (typeof snapshotDriftFields)[number];

export type SnapshotRecordDrift = {
  fields: SnapshotDriftField[];
  month: string;
  saved: MonthlySnapshot;
};

/** Records without prices: enough to tell whether a saved month still matches them. */
export type SnapshotDriftCheckRecords = Omit<SnapshotDriftRecords, "historicalQuotes" | "quoteCache">;

/** Differences under a rupee are rounding, not a changed record. */
const tolerance = 1;

export type SavedSnapshotRecalculation =
  | { ok: true; snapshot: MonthlySnapshot }
  | { ok: false; reason: string };

/**
 * The month as current records give it, keeping the saved month's ID. The
 * saved values play no part, so a month saved by hand comes back as automatic.
 */
export function recalculateSavedSnapshot(
  records: SnapshotDriftRecords,
  saved: MonthlySnapshot,
): SavedSnapshotRecalculation {
  const result = buildGeneratedMonthEndSnapshot({
    ...records,
    existingSnapshots: [],
    targetMonth: saved.month,
  });
  if (result.status !== "created" || !result.snapshot) {
    return {
      ok: false,
      reason: result.warnings[0] ?? "This month can't be worked out from your records.",
    };
  }
  return { ok: true, snapshot: { ...result.snapshot, id: saved.id } };
}

/**
 * Only months CogVest once worked out from records are checked, including ones
 * the user then reviewed; values typed in by hand never claimed to match
 * records. Estimated months are skipped, since CogVest rebuilds those itself.
 */
export function isDriftCheckedSnapshot(saved: MonthlySnapshot) {
  return saved.generated !== undefined && !isAutoGeneratedSnapshotProvisional(saved);
}

/**
 * Checks one saved month at a time against current records (#747), so a caller
 * can spread a long history over several frames. Every holding is valued at a
 * neutral price: the compared values never depend on prices, so price updates
 * never need a new check. A month that can't be worked out from records, or
 * isn't checked at all, gives null.
 */
export function createSnapshotDriftCheck(records: SnapshotDriftCheckRecords) {
  const neutralPrices: QuoteCache = Object.fromEntries(records.assets.map((asset) => [asset.id, {
    asOf: records.now.toISOString(), assetId: asset.id, currency: asset.currency, price: 1, source: "manual" as const,
  }]));
  const priced: SnapshotDriftRecords = { ...records, historicalQuotes: {}, quoteCache: neutralPrices };
  return (saved: MonthlySnapshot): SnapshotRecordDrift | null => {
    if (!isDriftCheckedSnapshot(saved)) return null;
    const recalculation = recalculateSavedSnapshot(priced, saved);
    if (!recalculation.ok) return null;
    const fields = snapshotDriftFields.filter((field) =>
      decimal(recalculation.snapshot[field]).minus(saved[field]).abs().greaterThan(tolerance));
    return fields.length > 0 ? { fields, month: saved.month, saved } : null;
  };
}

/** Saved months whose record-based values no longer match current records, by month. */
export function findSnapshotRecordDrift({
  monthlySnapshots,
  ...records
}: SnapshotDriftCheckRecords & { monthlySnapshots: readonly MonthlySnapshot[] }) {
  const check = createSnapshotDriftCheck(records);
  const drift = new Map<string, SnapshotRecordDrift>();
  for (const saved of monthlySnapshots) {
    const result = check(saved);
    if (result) drift.set(result.month, result);
  }
  return drift;
}

/** Where a saved month's values came from, in the words the month detail uses. */
export function snapshotSourceLabel(snapshot: MonthlySnapshot) {
  if (!snapshot.generated || snapshot.generated.source === "manual") return "Saved by you";
  return isAutoGeneratedSnapshotProvisional(snapshot) ? "Estimated" : "Automatic";
}
